--- 获取阵型克制倍率 (我方阵型 vs 敌方阵型)
function GetFormationCounterMult(myFormId, enemyFormId)
    if not FORMATION_COUNTER[myFormId] then return 1.0 end
    return FORMATION_COUNTER[myFormId][enemyFormId] or 1.0
end

--- 分析敌方兵种组成比例, 返回 { infantry=0.3, archer=0.5, ... }
function AnalyzeEnemyTroopComposition()
    local counts = {}; local total = 0
    for _, slot in ipairs(ENEMY_SLOTS or {}) do
        if slot.filled and slot.card then
            local t = slot.card.troopType or "infantry"
            counts[t] = (counts[t] or 0) + 1; total = total + 1
        end
    end
    local comp = {}
    for t, c in pairs(counts) do comp[t] = c / math.max(total, 1) end
    return comp
end

--- 评估某阵型对当前敌人的综合评分 (0~100, 50=中立)
function EvaluateFormationScore(formId)
    local form = nil
    for _, f in ipairs(FORMATIONS) do if f.id == formId then form = f; break end end
    if not form then return 50 end

    local score = 50
    -- 阵型属性加成
    score = score + (form.playerAtkMult - 1.0) * 30
    score = score + (form.playerDefMult - 1.0) * 20
    -- 敌方阵型克制
    local enemyFormId = gameState and gameState.enemyFormationId or DEFAULT_FORMATION_ID
    local counterMult = GetFormationCounterMult(formId, enemyFormId)
    score = score + (counterMult - 1.0) * 40
    -- 兵种适配
    local comp = AnalyzeEnemyTroopComposition()
    if form.archerAtkBonus > 0 and (comp.infantry or 0) > 0.3 then score = score + 8 end
    if form.counterDmgReflect > 0 and (comp.cavalry or 0) > 0.3 then score = score + 8 end

    return math.max(0, math.min(100, math.floor(score)))
end

