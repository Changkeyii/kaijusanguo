--- 按阵型车道权重随机选择车道 (返回 1~5)
function PickFormationLane()
    local weights = battleFormationLaneWeights
    if not weights then return math.random(1, 5) end
    local total = 0
    for _, w in ipairs(weights) do total = total + w end
    local r = math.random() * total
    local cum = 0
    for i, w in ipairs(weights) do
        cum = cum + w
        if r <= cum then return i end
    end
    return 3
end

